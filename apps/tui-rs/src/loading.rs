pub fn phrase(index: usize) -> &'static str {
    PHRASES[index % PHRASES.len()]
}

pub fn format_elapsed(seconds: u64) -> String {
    if seconds < 60 {
        format!("{seconds}s")
    } else {
        let minutes = seconds / 60;
        let remainder = seconds % 60;
        if remainder == 0 {
            format!("{minutes}m")
        } else {
            format!("{minutes}m {remainder}s")
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::collections::HashSet;

    #[test]
    fn matches_the_ink_loading_phrase_catalog() {
        assert_eq!(PHRASES.len(), 74);
        assert_eq!(PHRASES.iter().copied().collect::<HashSet<_>>().len(), 74);
        assert_eq!(PHRASES[0], "正在努力搬砖，请稍候...");
        assert_eq!(PHRASES[23], "加载的是字节，承载的是对技术的热爱...");
        assert_eq!(PHRASES[73], "马上完成，只差一个无法估时的小问题...");
    }

    #[test]
    fn formats_elapsed_time_like_the_ink_baseline() {
        assert_eq!(format_elapsed(12), "12s");
        assert_eq!(format_elapsed(60), "1m");
        assert_eq!(format_elapsed(125), "2m 5s");
    }
}
